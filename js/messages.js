let language = 'ja';
export function getLang() { return language; }
export function setLang(lang) {
  if (!Object.hasOwn(DICTIONARIES, lang)) throw new RangeError('Invalid language');
  language = lang;
}

export function t(key, params = {}) {
  const dictionary = DICTIONARIES[language];
  if (!Object.hasOwn(dictionary, key)) throw new Error(`Unknown message: ${key}`);
  return dictionary[key].replace(/\{(\w+)\}/g, (_, name) => {
    if (!Object.hasOwn(params, name)) throw new Error(`Missing parameter: ${name}`);
    return String(params[name]);
  });
}
